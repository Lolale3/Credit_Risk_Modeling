def psi(expected, actual, edges):
    e = np.clip(np.histogram(expected, bins = edges)[0] / len(expected), 1e-6, None)
    a = np.clip(np.histogram(actual, bins = edges)[0] / len(actual), 1e-6, None)
    return float(np.sum((a - e) * np.log(a / e)))

def psi_labels(expected, actual):
    cats = sorted(set(expected) | set(actual), key = str)
    e = np.clip(pd.Series(expected).value_counts(normalize = True).reindex(cats, fill_value = 0).to_numpy(), 1e-6, None)
    a = np.clip(pd.Series(actual).value_counts(normalize = True).reindex(cats, fill_value = 0).to_numpy(), 1e-6, None)
    return float(np.sum((a - e) * np.log(a / e)))

