def credit_history_months(df):
    issue = pd.to_datetime(df['issue_d'], format = "%b-%y")
    earliest = pd.to_datetime(df['earliest_cr_line'], format = "%b-%y")
    # two-digit years: 'Jan-62' parses as 2062, so shift any credit line that starts after the loan back a century
    future = earliest > issue
    earliest.loc[future] = earliest.loc[future] - pd.DateOffset(years=100)
    df['mths_since_earliest_cr_line'] = (issue.dt.year - earliest.dt.year) * 12 + (issue.dt.month - earliest.dt.month)
    df.drop(columns = ['earliest_cr_line', 'issue_d'], inplace = True)

