def _fmt(v):
    return f'{v:,.4g}'


class WoE_Binning(BaseEstimator, TransformerMixin):
    # Fits WoE bins on training data, then one-hot encodes each loan's bin (reference bins dropped).

    def __init__(self, numeric_features=None, categorical_features=None, max_bins=8,
                 min_bin_share=0.05, min_cat_share=0.02, iv_min=0.02, corr_max=0.75):
        self.numeric_features = numeric_features
        self.categorical_features = categorical_features
        self.max_bins = max_bins
        self.min_bin_share = min_bin_share
        self.min_cat_share = min_cat_share
        self.iv_min = iv_min
        self.corr_max = corr_max

    # ---------- fitting ----------
    def fit(self, X, y):
        bad = 1 - np.asarray(y, dtype=float)          # y is good_bad (1 = good)
        self.bins_ = {}
        for f in (self.numeric_features or []):
            if f in X.columns:
                self.bins_[f] = self._fit_numeric(X[f], bad)
        for f in (self.categorical_features or []):
            if f in X.columns:
                self.bins_[f] = self._fit_categorical(f, X[f], bad)
        self.iv_ = {f: b['iv'] for f, b in self.bins_.items()}

        self.dropped_low_iv_ = sorted(f for f, v in self.iv_.items() if v < self.iv_min)
        candidates = [f for f in self.bins_ if self.iv_[f] >= self.iv_min]
        woe_values = pd.DataFrame({f: self._woe_values(X[f], f) for f in candidates}, index=X.index)
        corr = woe_values.corr().abs().fillna(0)
        kept, self.dropped_corr_ = [], []
        for f in sorted(candidates, key=lambda f: -self.iv_[f]):
            partners = [k for k in kept if corr.loc[f, k] > self.corr_max]
            if partners:
                self.dropped_corr_.append((f, partners[0], round(float(corr.loc[f, partners[0]]), 2)))
            else:
                kept.append(f)
        self.selected_ = [f for f in candidates if f in kept]

        self.ref_categories_, self.columns_ = [], []
        for f in self.selected_:
            b = self.bins_[f]
            ref = b['labels'][int(np.argmin(b['woe']))]
            self.ref_categories_.append(f'{f}:{ref}')
            self.columns_ += [f'{f}:{lab}' for lab in b['labels'] if lab != ref]

        tables = []
        for f, b in self.bins_.items():
            t = b['table'].copy()
            t.insert(0, 'feature', f)
            t['IV'] = b['iv']
            t['selected'] = f in self.selected_
            tables.append(t)
        self.woe_table_ = pd.concat(tables, ignore_index=True)
        return self

    def _fit_numeric(self, x, bad):
        xv = pd.to_numeric(x, errors='coerce').to_numpy(dtype=float)
        nn = ~np.isnan(xv)
        total = len(xv)
        edges = []
        if nn.sum() > 0:
            qs = np.quantile(xv[nn], np.linspace(0, 1, self.max_bins + 1)[1:-1])
            edges = [e for e in np.unique(qs) if e < np.nanmax(xv)]

        def counts(e):
            idx = np.searchsorted(e, xv[nn], side='left')
            k = len(e) + 1
            return (np.bincount(idx, minlength=k).astype(float),
                    np.bincount(idx, weights=bad[nn], minlength=k))

        # merge bins that are too small into the neighbour with the closer bad rate
        while len(edges) > 0:
            n, b = counts(edges)
            small = np.where(n / total < self.min_bin_share)[0]
            if len(small) == 0:
                break
            i = small[np.argmin(n[small])]
            k = len(n)
            if i == 0:
                del edges[0]
            elif i == k - 1:
                del edges[k - 2]
            elif n[i] == 0:
                del edges[i - 1]
            else:
                br = np.divide(b, n, out=np.full_like(b, np.nan), where=n > 0)
                left, right = abs(br[i] - br[i - 1]), abs(br[i] - br[i + 1])
                if np.isnan(right) or (not np.isnan(left) and left <= right):
                    del edges[i - 1]
                else:
                    del edges[i]

        # merge neighbours until the bad rate is monotonic
        if len(edges) > 0:
            n, b = counts(edges)
            br = b / n
            if len(n) > 2:
                r = np.corrcoef(np.arange(len(n)), br)[0, 1]
                direction = np.sign(r) if np.isfinite(r) and r != 0 else 1.0
            else:
                direction = np.sign(br[-1] - br[0]) or 1.0
            while len(edges) > 0:
                n, b = counts(edges)
                violations = np.where(np.diff(b / n) * direction < 0)[0]
                if len(violations) == 0:
                    break
                del edges[violations[0]]

        edges = np.array(edges, dtype=float)
        n, b = counts(list(edges)) if nn.sum() > 0 else (np.array([0.0]), np.array([0.0]))
        if len(edges) == 0:
            labels = ['all']
        else:
            labels = ([f'<={_fmt(edges[0])}']
                      + [f'{_fmt(lo)}-{_fmt(hi)}' for lo, hi in zip(edges[:-1], edges[1:])]
                      + [f'>{_fmt(edges[-1])}'])
        n, b = list(n), list(b)
        if (~nn).any():
            labels.append('missing')
            n.append(float((~nn).sum()))
            b.append(float(bad[~nn].sum()))
        out = self._woe(labels, np.array(n), np.array(b), bad)
        out.update(kind='numeric', edges=edges)
        return out

    def _clean_cat(self, f, x):
        s = x.astype('string').str.strip().fillna('missing').replace('', 'missing').astype(object)
        return s.replace(CATEGORY_GROUPS.get(f, {}))

    def _fit_categorical(self, f, x, bad):
        s = self._clean_cat(f, x)
        share = s.value_counts(normalize=True)
        min_share = 0.0 if f == 'grade' else self.min_cat_share   # keep every grade, including G
        keep = set(share[share >= min_share].index)
        s = s.where(s.isin(keep), 'RARE')
        labels = sorted(s.unique())
        n = np.array([float((s == lab).sum()) for lab in labels])
        b = np.array([float(bad[(s == lab).to_numpy()].sum()) for lab in labels])
        out = self._woe(labels, n, b, bad)
        out.update(kind='categorical', keep=keep)
        return out

    @staticmethod
    def _woe(labels, n, b, bad):
        g = n - b
        G, B, k = float((bad == 0).sum()), float((bad == 1).sum()), len(labels)
        pg = (g + 0.5) / (G + 0.5 * k)      # +0.5 smoothing keeps WoE finite for empty cells
        pb = (b + 0.5) / (B + 0.5 * k)
        woe = np.log(pg / pb)
        table = pd.DataFrame({'bin': labels, 'n_obs': n.astype(int), 'prop_n_obs': n / n.sum(),
                              'bad_rate': np.divide(b, n, out=np.full_like(b, np.nan), where=n > 0),
                              'WoE': woe})
        return {'labels': labels, 'woe': woe, 'iv': float(np.sum((pg - pb) * woe)), 'table': table}

    # ---------- applying ----------
    def bin_labels(self, X, f):
        b = self.bins_[f]
        if b['kind'] == 'numeric':
            xv = pd.to_numeric(X[f], errors='coerce').to_numpy(dtype=float)
            nn = ~np.isnan(xv)
            n_value_bins = len(b['edges']) + 1
            labs = np.empty(len(xv), dtype=object)
            labs[nn] = np.array(b['labels'][:n_value_bins], dtype=object)[np.searchsorted(b['edges'], xv[nn], side='left')]
            labs[~nn] = 'missing'
            return labs
        s = self._clean_cat(f, X[f])
        return s.where(s.isin(b['keep']), 'RARE').to_numpy(dtype=object)

    def _woe_values(self, x, f):
        lookup = dict(zip(self.bins_[f]['labels'], self.bins_[f]['woe']))
        return np.array([lookup.get(l, 0.0) for l in self.bin_labels(x.to_frame(f), f)])

    def transform(self, X):
        cols = {}
        refs = set(self.ref_categories_)
        for f in self.selected_:
            labs = self.bin_labels(X, f)
            for lab in self.bins_[f]['labels']:
                name = f'{f}:{lab}'
                if name not in refs:
                    cols[name] = (labs == lab).astype(int)
        # a bin never seen in training gets all zeros, i.e. it is scored as the reference (riskiest) bin
        return pd.DataFrame(cols, index=X.index)[self.columns_]

